// Crown Draughts — the game's one authoritative server script (starhermit.txt
// `server=server.js`). The platform runs it in its sandboxed Jint host: a fresh
// engine per invocation, one classic script, no imports, every bit of state in
// the documents it returns. The rules are the client's own js/rules modules,
// written into the RULES block below by tools/build-server.mjs.
//
// It runs two kinds of session:
//
// 1. Hosted tables (room-bound sessions). A hosted table is a realtime room
//    (one team, a seat per house of the ruleset in `config.metadata.ruleset`);
//    when it starts the platform creates a session bound to it and calls
//    createSession with `ctx.room` (the frozen roster) and `ctx.presence`. This
//    script referees the whole round: it seats the roster (seat = roster
//    order; empty seats and the platform's AI seats play a one-ply greedy house),
//    validates every command against the rules with the sender the platform
//    names (`ctx.message.from`, never a seat or player from the payload),
//    plays the AI seats on its tick, adjudicates the optional turn deadline,
//    forfeits a player who left the room, and ends the round with `result`
//    (which the platform stores on the room before closing it), the winner's
//    `hosted-wins` total in `scores`, and Elo for a two-human table
//    (`eloUpdates`). Nothing a client says about the outcome is read.
//
//    Client → script (`ctx.message.data`):
//      { type: 'sync' }                                    the table, to the sender
//      { type: 'act', action: { type: 'move', piece, path } | { type: 'resign' |
//        'offerDraw' | 'acceptDraw' | 'declineDraw' } }    for the sender's seat
//      { type: 'chat', text }                              to the table (≤ 200 chars)
//    Script → clients (`broadcast`):
//      { type: 'table', ruleset, seed, seats: [{ name, ai, userId }], moves,
//        ply, deadlineAt, over }   after every change and on sync; `moves` is
//        the game log, a move as [piece, r1, c1, r2, c2, …] and anything else
//        as a letter and the player ('r' resign, 't' timeout, 'o' offer draw,
//        'a' accept, 'd' decline), which clients replay through the same rules
//      { type: 'chat', seat, name, text }
//      `over` is null until the round ends, then { winner, reason, plies,
//      elapsedMs, breakdowns, ratings, recorded: true }.
//
// 2. Score posting (any other session — the practice session the client opens
//    with sessions.practice()): a finished solo round's total arrives as
//    { type: 'result', scores: { 'high-score': n } }; it is range-checked
//    against BOARDS, returned in `scores` and the session ends — the
//    behaviour the former score-script.js had.
